CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ts INTEGER NOT NULL,
  sid TEXT NOT NULL,
  ip TEXT NOT NULL,
  kind TEXT NOT NULL,
  slug TEXT NOT NULL,
  likes TEXT NOT NULL DEFAULT '',
  nopes TEXT NOT NULL DEFAULT '',
  age INTEGER,
  with_ TEXT,
  moods TEXT NOT NULL DEFAULT '',
  time INTEGER,
  kit TEXT NOT NULL DEFAULT '',
  dev TEXT,
  lang TEXT
);
CREATE INDEX IF NOT EXISTS events_ip_ts ON events (ip, ts);
CREATE INDEX IF NOT EXISTS events_ts ON events (ts);
CREATE TABLE IF NOT EXISTS auto_tags (
  slug TEXT PRIMARY KEY,
  hash TEXT NOT NULL,
  tags TEXT NOT NULL,
  ts INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS kv (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL,
  ts INTEGER NOT NULL
);
